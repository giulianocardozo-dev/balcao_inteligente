function isPointInPolygon(lat: number, lon: number, ring: [number, number][]): boolean {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const xi = ring[i][0];
    const yi = ring[i][1];
    const xj = ring[j][0];
    const yj = ring[j][1];

    const intersect =
      yi > lon !== yj > lon &&
      lat < ((xj - xi) * (lon - yi)) / (yj - yi || 1e-9) + xi;
    if (intersect) inside = !inside;
  }
  return inside;
}

export function detectUfFromCoordinates(lat: number, lon: number): string | null {
  // Outside Brazil bounding box -> return null so caller keeps default ('SP')
  if (lat < -34.0 || lat > 5.5 || lon < -74.2 || lon > -34.5) {
    return null;
  }

  for (const poly of UF_POLYGONS) {
    if (isPointInPolygon(lat, lon, poly.ring)) {
      return poly.uf;
    }
  }

  // Fallback inside Brazil: nearest state centroid
  let closestUf: string | null = null;
  let minDistSq = Infinity;
  for (const c of UF_CENTROIDS) {
    const dLat = lat - c.lat;
    const dLon = lon - c.lon;
    const distSq = dLat * dLat + dLon * dLon;
    if (distSq < minDistSq) {
      minDistSq = distSq;
      closestUf = c.uf;
    }
  }
  return closestUf;
}
